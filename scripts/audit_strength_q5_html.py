"""Static artifact and isolated control checks; preserve browser-policy blocker."""
from pathlib import Path
from html.parser import HTMLParser
from datetime import datetime,timezone
import argparse,json,re,subprocess,sys
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT))
from src.data_contract import file_hash,write_json


class Inspect(HTMLParser):
    def __init__(self):super().__init__();self.ids=[];self.links=[];self.external=[];self.slides=0;self.fragments=[]
    def handle_starttag(self,tag,attrs):
        a=dict(attrs)
        if a.get('id'):self.ids.append(a['id'])
        if tag=='section' and a.get('class')=='slide':self.slides+=1
        if tag=='a' and a.get('href'):self.links.append(a['href'])
        for key,value in a.items():
            if not value:continue
            if key in ('href','xlink:href') and value.startswith('#'):self.fragments.append(value[1:])
            self.fragments.extend(re.findall(r'url\(#([^)]+)\)',value))
        if tag in ('script','img','link') and a.get('src',a.get('href','')).startswith(('http:','https:')):self.external.append(a)


def run(preview=False):
    if preview:path=ROOT/'outputs/test_tmp/q5_layout/index.html'
    else:
        pointer=json.loads((ROOT/'outputs/logs/strength_q5_closeout/current.json').read_text());path=ROOT/pointer['HTML']
    content=path.read_text(encoding='utf-8');parser=Inspect();parser.feed(content);checks={}
    checks['three_slides']=parser.slides==3;checks['unique_ids']=len(parser.ids)==len(set(parser.ids))
    checks['all_SVG_glyph_and_clip_references']=all(ref in set(parser.ids) for ref in parser.fragments)
    checks['required_controls']=all(x in parser.ids for x in ('previous','next','page','appendix','appendixButton','closeAppendix','full','q5-data'))
    checks['no_external_resources']=not parser.external
    checks['offline_source_links']=all((path.parent/h).resolve().exists() for h in parser.links if not h.startswith(('http:','https:','#')))
    embedded=json.loads(re.search(r'<script id="q5-data" type="application/json">(.*?)</script>',content,re.S).group(1))
    checks['actual_prediction_sample']=embedded['prediction_matches']==21413
    checks['binary_not_WDL']=not embedded['full_WDL_prediction']
    checks['unconditional_claim_absent']=not embedded['unconditional_coverage_certified']
    # Source HTML was generated by us. The stub only checks our own JS functions;
    # it does not load a page, use a browser or work around the rejected file URL.
    result=subprocess.run(['node',str(ROOT/'scripts/audit_strength_q5_html.cjs'),str(path)],capture_output=True,text=True,check=True)
    controls=json.loads(result.stdout);checks['isolated_control_logic']=controls['passed']
    report=dict(passed=all(checks.values()),static_checks=checks,control_check=controls,HTML_sha256=file_hash(path),
        audit_code_sha256=file_hash(Path(__file__)),control_code_sha256=file_hash(ROOT/'scripts/audit_strength_q5_html.cjs'),
        executed_utc=datetime.now(timezone.utc).isoformat(),
        actual_browser_validation=False,browser_attempt_status='blocked_by_browser_security_policy',
        browser_blocked_action='file:// local HTML preview; allowed browser URL protocols http/https; no alternate browser navigation attempted',
        rendered_figures_reviewed_by_AI=True,actual_projector_validation=False,human_review=False,
        next_manual_check='Open final HTML normally on the presentation computer; verify three pages, appendix, arrow keys, fullscreen, offline display and print.',
        preview_only=preview)
    out=ROOT/('outputs/test_tmp/q5_layout/static_review.json' if preview else 'outputs/logs/strength_q5_closeout/browser_review.json')
    write_json(out,report);print(json.dumps(report))
    if not report['passed']:raise SystemExit(1)


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--preview',action='store_true');run(p.parse_args().preview)
